# =====================================================================
# PARCIAL 2 - PROGRAMACIÓN I: SISTEMA DE MONITOREO DE INVERNADERO
# =====================================================================

# 1. CONSTANTES DEL SISTEMA (Definidas en la Tabla de Identificadores)
TEMP_MIN_VALIDA = -10.0
TEMP_MAX_VALIDA = 60.0
HUM_MIN_VALIDA = 0.0
HUM_MAX_VALIDA = 100.0

TEMP_MIN_OPTIMA = 18.0
TEMP_MAX_OPTIMA = 26.0
HUM_MIN_OPTIMA = 60.0
HUM_MAX_OPTIMA = 80.0

TEMP_MIN_CRITICA = 12.0
TEMP_MAX_CRITICA = 32.0
HUM_MIN_CRITICA = 40.0
HUM_MAX_CRITICA = 90.0

MAX_LECTURAS = 8

# 2. INICIALIZACIÓN DE VARIABLES Y ESTRUCTURAS DE CONTROL
lectura = 0
continuar = True
sumTemp = 0.0
sumHum = 0.0

# Inicialización de mínimos con valores altos y máximos con valores bajos
minTemp = 999.0
maxTemp = -999.0
minHum = 999.0
maxHum = -999.0

# Acumuladores de cadenas para las secuencias solicitadas
secuenciaTemp = ""
secuenciaHum = ""
estado_final = ""

print("=====================================================")
print("  SISTEMA DE SEGUIMIENTO Y CONTROL - INVERNADERO DE FRESA")
print("=====================================================")

# 3. CICLO DE CONTROL PRINCIPAL (Basado en el diagrama de flujo)
while continuar and lectura < MAX_LECTURAS:
    dato_valido = False
    temp = 0.0
    hum = 0.0

    # 3.1 Validación estricta de datos del sensor
    while not dato_valido:
        print(f"\n--- Intento de Lectura {lectura + 1} ---")
        temp = float(input("Ingrese la temperatura registrada (°C): "))
        hum = float(input("Ingrese la humedad relativa registrada (%): "))

        if (TEMP_MIN_VALIDA <= temp <= TEMP_MAX_VALIDA) and (HUM_MIN_VALIDA <= hum <= HUM_MAX_VALIDA):
            dato_valido = True
        else:
            print("Dato inválido. Ingrese nuevamente la lectura (el dato fuera de rango no se cuenta).")

    # 3.2 Actualización de contador y estadísticas por cada lectura válida
    lectura = lectura + 1

    sumTemp = sumTemp + temp
    sumHum = sumHum + hum

    if temp < minTemp:
        minTemp = temp
    if temp > maxTemp:
        maxTemp = temp

    if hum < minHum:
        minHum = hum
    if hum > maxHum:
        maxHum = hum

    # Registro en las secuencias acumuladas separadas por punto y coma
    secuenciaTemp = secuenciaTemp + str(temp) + ";"
    secuenciaHum = secuenciaHum + str(hum) + ";"

    # 3.3 Evaluación Jerárquica de Estados
    if (temp < TEMP_MIN_CRITICA or temp > TEMP_MAX_CRITICA) or (hum < HUM_MIN_CRITICA or hum > HUM_MAX_CRITICA):
        estado_final = "Alerta crítica"
        print(f"Estado: {estado_final} -> ¡Alguna variable alcanzó un valor crítico! Activando protocolo de emergencia.")
        continuar = False

    elif (TEMP_MIN_OPTIMA <= temp <= TEMP_MAX_OPTIMA) and (HUM_MIN_OPTIMA <= hum <= HUM_MAX_OPTIMA):
        estado_final = "Cultivo estabilizado"
        print(f"Estado: {estado_final} -> Ambas variables han vuelto a estar dentro del rango óptimo.")
        continuar = False

    else:
        # Estado en Observación y determinación de acciones correctivas
        print("Estado: Observación. Acciones correctivas a aplicar:")
        if temp > TEMP_MAX_OPTIMA:
            print("  - Ventilar")
        elif temp < TEMP_MIN_OPTIMA:
            print("  - Encender calefacción")

        if hum > HUM_MAX_OPTIMA:
            print("  - Deshumidificar")
        elif hum < HUM_MIN_OPTIMA:
            print("  - Nebulizar (riego por neblina)")

        # Comprobación del límite de lecturas para revisión técnica
        if lectura == MAX_LECTURAS:
            estado_final = "Revisión técnica"
            print(f"Estado: {estado_final} -> Se completaron 8 lecturas sin estabilización ni valores críticos.")

# 4. SALIDA DE RESULTADOS FINALES Y ESTADÍSTICAS
print("\n=====================================================")
print("                   RESULTADO FINAL                   ")
print("=====================================================")
print(f"Resultado: {estado_final}.")
print(f"Número total de lecturas tomadas: {lectura}")

if lectura > 0:
    promedioTemp = sumTemp / lectura
    promedioHum = sumHum / lectura

    print(f"Temperatura: mínima {minTemp} – máxima {maxTemp} – promedio {promedioTemp:.2f}")
    print(f"Humedad: mínima {minHum} – máxima {maxHum} – promedio {promedioHum:.2f}")
    print(f"Secuencia de temperaturas: {secuenciaTemp}")
    print(f"Secuencia de humedades: {secuenciaHum}")
print("=====================================================")