# ==========================================
# PARCIAL 2 - PROGRAMACIÓN I: INVERNADERO
# ==========================================

# 1. INICIALIZACIÓN DE CONSTANTES (Tabla de Identificadores)
TEMP_MIN_VALIDA = -10.0
TEMP_MAX_VALIDA = 60.0
HUM_MIN_VALIDA = 0.0
HUM_MAX_VALIDA = 100.0

TEMP_MIN_OPTIMA = 18.0
TEMP_MAX_OPTIMA = 26.0
HUM_MIN_OPTIMA = 60.0
HUM_MAX_OPTIMA = 80.0

TEMP_MIN_CRITICA = 12.0
TEMP_MAX_CRITICA = 32.0
HUM_MIN_CRITICA = 40.0
HUM_MAX_CRITICA = 90.0

MAX_LECTURAS = 8

# 2. INICIALIZACIÓN DE VARIABLES
lectura = 0
continuar = True
sumTemp = 0.0
sumHum = 0.0
minTemp = 999.0
maxTemp = -999.0
minHum = 999.0
maxHum = -999.0
secuenciaTemp = ""
secuenciaHum = ""
estado_final = ""

print("=== SISTEMA DE MONITOREO DE INVERNADERO ===")

# 3. CICLO DE CONTROL PRINCIPAL
while continuar and lectura < MAX_LECTURAS:
    # Validación de datos del sensor
    dato_valido = False
    temp = 0.0
    hum = 0.0

    while not dato_valido:
        temp = float(input(f"\nLectura {lectura + 1} - Ingrese la temperatura (°C): "))
        hum = float(input(f"Lectura {lectura + 1} - Ingrese la humedad relativa (%): "))

        if (TEMP_MIN_VALIDA <= temp <= TEMP_MAX_VALIDA) and (HUM_MIN_VALIDA <= hum <= HUM_MAX_VALIDA):
            dato_valido = True
        else:
            print("Dato inválido. Ingrese nuevamente la lectura (no se cuenta).")

    # Incremento de contador y actualización de estadísticas
    lectura = lectura + 1

    sumTemp = sumTemp + temp
    sumHum = sumHum + hum

    if temp < minTemp:
        minTemp = temp
    if temp > maxTemp:
        maxTemp = temp

    if hum < minHum:
        minHum = hum
    if hum > maxHum:
        maxHum = hum

    secuenciaTemp = secuenciaTemp + str(temp) + ";"
    secuenciaHum = secuenciaHum + str(hum) + ";"

    # Evaluación Jerárquica de Estados
    if (temp < TEMP_MIN_CRITICA or temp > TEMP_MAX_CRITICA) or (hum < HUM_MIN_CRITICA or hum > HUM_MAX_CRITICA):
        estado_final = "Alerta crítica"
        print(f"Estado: {estado_final} -> ¡Activar protocolo de emergencia del invernadero!")
        continuar = False

    elif (TEMP_MIN_OPTIMA <= temp <= TEMP_MAX_OPTIMA) and (HUM_MIN_OPTIMA <= hum <= HUM_MAX_OPTIMA):
        estado_final = "Condiciones óptimas / Cultivo estabilizado"
        print(f"Estado: {estado_final}")
        continuar = False

    else:
        # Estado de Observación y Acciones Correctivas
        print("Estado: Observación. Acciones correctivas necesarias:")
        if temp > TEMP_MAX_OPTIMA:
            print("- Ventilar")
        elif temp < TEMP_MIN_OPTIMA:
            print("- Encender calefacción")

        if hum > HUM_MAX_OPTIMA:
            print("- Deshumidificar")
        elif hum < HUM_MIN_OPTIMA:
            print("- Nebulizar (riego por neblina)")

        if lectura == MAX_LECTURAS:
            estado_final = "Revisión técnica"
            print(f"Estado: {estado_final} -> Se completaron 8 lecturas sin estabilizarse.")

# 4. RESULTADOS FINALES Y ESTADÍSTICAS
print("\n==========================================")
print("           RESULTADO FINAL                ")
print("==========================================")
print(f"Resultado: {estado_final}")
print(f"Número total de lecturas tomadas: {lectura}")

if lectura > 0:
    promedioTemp = sumTemp / lectura
    promedioHum = sumHum / lectura
    print(f"Temperatura: mínima {minTemp} – máxima {maxTemp} – promedio {promedioTemp:.2f}")
    print(f"Humedad: mínima {minHum} – máxima {maxHum} – promedio {promedioHum:.2f}")
    print(f"Secuencia de temperaturas: {secuenciaTemp}")
    print(f"Secuencia de humedades: {secuenciaHum}")
print("==========================================")